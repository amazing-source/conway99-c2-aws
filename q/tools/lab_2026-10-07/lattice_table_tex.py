"""The table of the 156 lattices as a LaTeX longtable (C2 lab, 2026-10-07). GENERATED from lemma/PROOF_C2/B_TABLE_156.json (itself
generated by lattice_table.py from the tracker and the checked reports) and from the two re-run reports; nothing typed by hand.
The printed root type groups equal components (a_3^4a_1^4a_1^4 -> a_3^4a_1^8) and, when the fifth argument is given
(measures/codex_exact_lattice_identity.json), is ASSERTED equal to the exact root type computed there for each of the 156 lattices.

  .venv/Scripts/python.exe scripts/cloud/lattice_table_tex.py <B_TABLE_156.json> <RERUN_28_CHECK json> <out.tex>

Output: one longtable (booktabs), no preamble: id, root system (math mode), method code, pairs, pairs excluded by a frame search,
pairs through T18, pairs through T20. For the lattices of the old pair-list methods (codes H, F, H3) the stored records of 27-29/09
give no checked count; their row carries the pairs of the whole-lattice re-run of 07/10 with engine v10 (identity symmetry: all
pairs up to the Weyl group and the sign of y_2), marked with a dagger; a lattice whose re-run is not accepted yet is marked so."""
import sys, json


def n(x): return "" if x is None else "{:,}".format(x).replace(",", "{,}")


def canonical(roots):
    """ADE type with equal components grouped: 'a_3^4a_1^4a_1^4' -> ('a_3^4a_1^8', {'a3': 4, 'a1': 8}); order of first appearance kept"""
    import re, collections
    c = collections.OrderedDict()
    for t, k, e in re.findall(r"([ade])_\{?(\d+)\}?(?:\^\{?(\d+)\}?)?", roots or ""): c[(t, int(k))] = c.get((t, int(k)), 0) + int(e or 1)
    tex = "".join("%s_%s%s" % (t, k if k < 10 else "{%d}" % k, "" if m == 1 else ("^%d" % m if m < 10 else "^{%d}" % m)) for (t, k), m in c.items())
    return tex, {"%s%d" % (t, k): m for (t, k), m in c.items()}


def main():
    T = json.load(open(sys.argv[1])); R28 = json.load(open(sys.argv[2])); out = sys.argv[3]
    BS = chr(92); head = "id & roots & method & pairs & by search & via $T_{18}$ & via $T_{20}$" + BS + BS
    X105 = json.load(open(sys.argv[4])) if len(sys.argv) > 4 else None
    EX = {"%03d" % r["id"]: r["root_type"] for r in json.load(open(sys.argv[5]))["records"]} if len(sys.argv) > 5 else None    # exact root types (independent program)
    LAB = {"S": "enum.", "SD": "enum.+W", "GD": "lists+W", "G": "lists", "O": "Leech", "H": "2nd run", "F": "2nd run", "H3": "2nd run",
           "P": "Prop.~" + BS + "ref{prop:pack}", "EP": "Prop.~" + BS + "ref{prop:pack}", "SP": "Prop.~" + BS + "ref{prop:pack}", "So": "Prop.~" + BS + "ref{prop:153}", "B": "Prop.~" + BS + "ref{prop:143}"}
    L = ["% GENERATED by q/tools/lab_2026-10-07/lattice_table_tex.py from lemma/PROOF_C2/B_TABLE_156.json and measures/RERUN_28_CHECK_2026-10-07.json; do not edit.",
         "% inputs of B_TABLE_156.json (sha256, 16 hex): " + "; ".join("%s %s" % kv for kv in sorted(T["inputs"].items())),
         BS + "begin{longtable}{r l l r r r r}",
         BS + "caption{The 156 lattices. The isometry classes are those of Borcherds's classification " + BS + "cite{Bor}. The column " + BS + "emph{roots} gives the type of the root system, "
         "equal components grouped; it was recomputed exactly from the input data (Section~" + BS + "ref{sec:lattices}). The identifiers 000--155 are the numbering of this work. "
         "Method: " + BS + "emph{enum.}: main enumeration of the pairs of normals, every pair excluded by a witness, by search or by transfer; "
         + BS + "emph{enum.+W}: the same, with pairs excluded through $T_{18}$ and $T_{20}$ by a certified witness; "
         + BS + "emph{lists}, " + BS + "emph{lists+W}: pairs produced by a separate program; " + BS + "emph{Leech}: the odd Leech lattice, by classes of pairs; "
         + BS + "emph{2nd run}: treated in September on lists of pairs and again in full on 7 October with the final program ($" + BS + "dagger$: pairs of that second run, "
         "enumerated up to the Weyl group only); a proposition number: excluded without enumeration.}" + BS + "label{tab:156}" + BS + BS,
         BS + "toprule", head, BS + "midrule", BS + "endfirsthead", BS + "toprule", head, BS + "midrule", BS + "endhead", BS + "bottomrule", BS + "endfoot"]
    tot = [0, 0, 0, 0]; dag = 0
    for r in T["rows"]:
        ctex, ctype = canonical(r["roots"] if r["roots"] not in ("(none)", None) else "")
        if EX is not None: assert ctype == EX[r["id"]], "root type of %s differs from the exact recomputation: %s / %s" % (r["id"], ctype, EX[r["id"]])
        roots = "---" if not ctex else "$%s$" % ctex
        pairs, search, mark = r["pairs"], r["search"], ""
        if r["id"] == "105" and X105: pairs = X105["pairs"]; search = X105["search"]; mark = "$^{" + BS + "dagger}$"; dag += 1
        if r["method"] in ("H", "F", "H3") and r["id"] in R28:
            c = R28[r["id"]]
            if c["ok"]: pairs = c["pairs"]; search = c["verdict_classes"].get("excl_search", 0); mark = "$^{" + BS + "dagger}$"; dag += 1
            else: mark = " (re-run in progress)"
        if not mark:
            for i, k in enumerate(("pairs", "search", "T18", "T20")): tot[i] += r[k] or 0
        L.append("%s & %s & %s & %s%s & %s & %s & %s" % (r["id"], roots, LAB[r["method"]], n(pairs), mark, n(search), n(r["T18"]), n(r["T20"])) + BS + BS)
    L += [BS + "midrule", BS + "multicolumn{3}{l}{total (rows without $" + BS + "dagger$)} & %s & %s & %s & %s" % tuple(n(x) for x in tot) + BS + BS, BS + "end{longtable}"]
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    print("rows %d; rows with a dagger %d; totals without dagger: pairs %s, search %s, T18 %s, T20 %s" % (len(T["rows"]), dag, *["{:,}".format(x) for x in tot]))


if __name__ == "__main__":
    main()
