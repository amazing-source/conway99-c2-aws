"""The table of the 156 lattices as a LaTeX longtable (C2 lab, 2026-10-07). GENERATED from lemma/PROOF_C2/B_TABLE_156.json (itself
generated by lattice_table.py from the tracker and the checked reports) and from the two re-run reports; nothing typed by hand.

  .venv/Scripts/python.exe scripts/cloud/lattice_table_tex.py <B_TABLE_156.json> <RERUN_28_CHECK json> <out.tex>

Output: one longtable (booktabs), no preamble: id, root system (math mode), method code, pairs, pairs excluded by a frame search,
pairs through T18, pairs through T20. For the lattices of the old pair-list methods (codes H, F, H3) the stored records of 27-29/09
give no checked count; their row carries the pairs of the whole-lattice re-run of 07/10 with engine v10 (identity symmetry: all
pairs up to the Weyl group and the sign of y_2), marked with a dagger; a lattice whose re-run is not accepted yet is marked so."""
import sys, json


def n(x): return "" if x is None else "{:,}".format(x).replace(",", "{,}")


def main():
    T = json.load(open(sys.argv[1])); R28 = json.load(open(sys.argv[2])); out = sys.argv[3]
    BS = chr(92); head = "id & roots & method & pairs & by search & via $T_{18}$ & via $T_{20}$" + BS + BS
    L = ["% GENERATED by q/tools/lab_2026-10-07/lattice_table_tex.py from lemma/PROOF_C2/B_TABLE_156.json and measures/RERUN_28_CHECK_2026-10-07.json; do not edit.",
         "% inputs of B_TABLE_156.json (sha256, 16 hex): " + "; ".join("%s %s" % kv for kv in sorted(T["inputs"].items())),
         BS + "begin{longtable}{r l l r r r r}",
         BS + "caption{The 156 lattices. The classification and the root systems are Borcherds' " + BS + "cite{Bor}; the root systems are written as in his table, "
         "the grouping of equal components included (it is his, and it is not collapsed here). The identifiers 000--155 are the numbering used in this work, not his. Method: S stream sweep; SD stream sweep with pairs through $T_{18}$, $T_{20}$; GD, G Golay pair files; O the odd Leech lattice; "
         "H, F, H3 pair lists of 27--29 September; P, EP, SP packing (Proposition~" + BS + "ref{prop:pack}; EP and SP: also by earlier arguments not used here); "
         "So decomposable lattice (Proposition~" + BS + "ref{prop:153}); B budget identity (Proposition~" + BS + "ref{prop:143}). "
         "$" + BS + "dagger$: pairs of the whole-lattice re-run with the archived engine (identity symmetry).}" + BS + "label{tab:156}" + BS + BS,
         BS + "toprule", head, BS + "midrule", BS + "endfirsthead", BS + "toprule", head, BS + "midrule", BS + "endhead", BS + "bottomrule", BS + "endfoot"]
    tot = [0, 0, 0, 0]; dag = 0
    for r in T["rows"]:
        roots = "---" if r["roots"] in ("(none)", "", None) else "$%s$" % r["roots"]
        pairs, search, mark = r["pairs"], r["search"], ""
        if r["method"] in ("H", "F", "H3") and r["id"] in R28:
            c = R28[r["id"]]
            if c["ok"]: pairs = c["pairs"]; search = c["verdict_classes"].get("excl_search", 0); mark = "$^{" + BS + "dagger}$"; dag += 1
            else: mark = " (re-run in progress)"
        if not mark:
            for i, k in enumerate(("pairs", "search", "T18", "T20")): tot[i] += r[k] or 0
        L.append("%s & %s & %s & %s%s & %s & %s & %s" % (r["id"], roots, r["method"], n(pairs), mark, n(search), n(r["T18"]), n(r["T20"])) + BS + BS)
    L += [BS + "midrule", BS + "multicolumn{3}{l}{total (rows without $" + BS + "dagger$)} & %s & %s & %s & %s" % tuple(n(x) for x in tot) + BS + BS, BS + "end{longtable}"]
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    print("rows %d; rows with a dagger %d; totals without dagger: pairs %s, search %s, T18 %s, T20 %s" % (len(T["rows"]), dag, *["{:,}".format(x) for x in tot]))


if __name__ == "__main__":
    main()
